def label_changes(kind, operator, value):
    changes=[row[3:] for row in STATIC_LABELS if row[:3]==(kind,operator,value)]
    if operator=='eq' and isinstance(value,str) and kind in ('worlds_top5_champion','career_top5_champion'):
        worlds=kind=='worlds_top5_champion'
        changes.append((f'{value} w TOP 5 '+('na Worlds' if worlds else 'kariery'),
            f'{value} in '+('Worlds' if worlds else 'career')+' top 5 played',
            f'{value} w jego TOP 5 według liczby gier '+('na Worlds' if worlds else 'w karierze'),
            f'{value} in his top 5 champions by games played '+('at Worlds' if worlds else 'in his career')))
    if kind=='worlds_games' and operator in ('gt','lt') and type(value) is int:
        pl,en=('Ponad','Over') if operator=='gt' else ('Poniżej','Under')
        changes.append((f'{pl} {value} gier na Worlds',f'{en} {value} games at Worlds',
            f'{pl} {value} gier na Worlds (z play-in)',f'{en} {value} games at Worlds (including play-in)'))
    if kind=='worlds_group_exit_before' and operator=='eq' and type(value) is int and 2012<=value<=2023:
        new_pl=f'Choć raz odpadł w grupie Worlds przed {value} (główny turniej)'
        new_en=f'Eliminated in Worlds main-event groups at least once before {value}'
        changes.extend([
            (f'Odpadł w fazie grupowej głównego turnieju Worlds przynajmniej raz przed {value}',
             f'Eliminated in the Worlds main-event group stage at least once before {value}',new_pl,new_en),
            (f'Odpadł w grupie Worlds przynajmniej raz przed {value}',f'Eliminated in Worlds groups before {value}',new_pl,new_en),
        ])
    return changes


def clarify_default_labels(apps,schema_editor):
    Condition=apps.get_model('dailies','DailySlotCondition')
    database=schema_editor.connection.alias
    for clue in Condition.objects.using(database).all().iterator():
        updates={}
        for old_pl,old_en,new_pl,new_en in label_changes(clue.condition_type,clue.operator,clue.value):
            if clue.label_pl==old_pl and old_pl!=new_pl: updates['label_pl']=new_pl
            if clue.label_en==old_en and old_en!=new_en: updates['label_en']=new_en
        if updates: Condition.objects.using(database).filter(pk=clue.pk).update(**updates)


